export function translate(locale:Locale,message:string,values:Record<string,string|number>={}):string {
  const key=message.trim();
  const translated=locale==="en"?(english[key]??key):key;
  const result=message.slice(0,message.indexOf(key))+translated+message.slice(message.indexOf(key)+key.length);
  return result.replace(/\{(\w+)\}/g,(match,key:string)=>String(values[key]??match));
}
export function errorText(locale:Locale,error:unknown):string {
  const message=error instanceof Error?error.message:typeof error==="string"?error:"暫時無法完成操作。";
  if(/Failed to fetch|fetch failed|NetworkError|Load failed|Network request failed/i.test(message))return translate(locale,"網絡連線失敗，請檢查連線後重試。");
  if(locale==="en" && /\p{Script=Han}/u.test(message) && !english[message.trim()])return translate(locale,"請確認表單欄位。");
  if(/^(Invalid (option|input)|Too (big|small))/.test(message))return translate(locale,"請確認表單欄位。");
  return translate(locale,message);
}
export function categoryLabel(id:CategoryId,locale:Locale):string {
  return translate(locale,CATEGORIES.find(category=>category.id===id)?.name??id);
}
export function monthLabel(month:string,locale:Locale):string {
  return new Intl.DateTimeFormat(locale==="en"?"en-HK":"zh-HK",{month:"short",timeZone:"UTC"}).format(new Date(month+"-01T00:00:00Z"));
}
export function dateLocale(locale:Locale):string { return locale==="en"?"en-HK":"zh-HK"; }
export function unitLabel(locale:Locale,count:number,unit:"receipts"|"transactions"|"pages"):string {
  if(locale==="zh-Hant")return {receipts:"份",transactions:"筆",pages:"頁"}[unit];
  return count===1?unit.slice(0,-1):unit;
}
